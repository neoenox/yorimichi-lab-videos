def mk(slug, title, head, hook, answer, notes, pron, scenes):
    (R / 'data' / f'{slug}_pron.json').write_text(json.dumps(pron, ensure_ascii=False), encoding='utf8')
    V = lambda n: f'assets/{slug}/fv/clip{n}.mp4'
    sc = []
    for i, s in enumerate(scenes):
        d = dict(text=s['text'], big=s['big'].replace('、', ''), sub=s['sub'].replace('、', ''), src=s['src'], vid=V(i + 1), dim=0.7, viz=s['viz'])

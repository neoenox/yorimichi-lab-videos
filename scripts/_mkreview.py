import sys
theme, out, focus, cal = sys.argv[1:5]
d = f'docs/themes/{theme}/'
head = f'''あなたは歴史解説動画の台本の査読者です。以下の「事実確認メモ」と「台本」を読み、評価だけをしてください（書き直しは禁止）。

観点：
A. 事実の誤り・取り違え（Web検索で照合してください。新しい事実を挙げる場合は出典のURLか書名を必ず付けること）。特に、日付と暦（{cal}）、人名、地名、数字。
B. 台本が、メモで確認できた範囲を超えて断定していないか（特に、{focus}）。
C. 音声で聞いたとき誤解されやすい言い方。
D. 「分かること」と「分からないこと」の線引きは適切か。
E. 構成・分量（約14〜16分、12章。ナレーションの文字数は3,300〜3,800字を目安）。

注意：メモの「台本で言わないこと」は、原典が未確認のため意図的に言っていません。指摘する場合は、出典つきで。研究者名は動画で出しません。

出力形式：総評（3行）／指摘の表（No・重大度 高中低・該当箇所・理由・出典）／問題なしと判断した主張／自信の低い判断。

=== 事実確認メモ ===
'''
open(out, 'w', encoding='utf8').write(head + open(d + '08_fact_check.md', encoding='utf8').read() + '\n\n=== 台本 ===\n' + open(d + '09_script_v1.md', encoding='utf8').read())
